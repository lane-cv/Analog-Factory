const {chromium} = require('playwright');
const fs = require('fs');
const path = require('path');
const evidence = process.env.AF_BROWSER_ARTIFACTS || '/tmp/analog-factory-browser-evidence';
fs.mkdirSync(evidence, {recursive:true});
const baseURL = process.env.AF_URL || 'http://127.0.0.1:8765';
(async () => {
const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1500,height:1050}});
const errors=[]; page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error') console.log('CONSOLE',message.text());});
await page.goto(baseURL);
await page.locator('#new-project').click();
await page.locator('#new-project-form [name=name]').fill('Browser validation');
const createdResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/projects' && response.request().method() === 'POST');
await page.locator('#new-project-form button[type=submit]').click();
const createdProject = await (await createdResponse).json();
await page.waitForFunction(id => document.querySelector('#project-select').value === id, createdProject.id);
await page.locator('.hero-card').waitFor();
console.log('CREATE',await page.locator('#footer-project').innerText());
await page.screenshot({path:path.join(evidence, 'overview.png'),fullPage:true});
await page.locator('#run-primary').click();
await page.waitForFunction(()=>document.querySelector('#log-label').textContent.includes('succeeded'),{timeout:30000});
await page.locator('.metric-item').first().waitFor();
console.log('SIMULATE',await page.locator('#log-label').innerText(),'TRACES',await page.locator('[data-trace]').count());
await page.locator('.metric-item').first().click();
console.log('EVIDENCE',await page.locator('#metric-evidence').innerText());
await page.screenshot({path:path.join(evidence, 'simulation.png'),fullPage:true});
await page.locator('[data-file="testbenches/pre.cir"]').click();
const source=await page.locator('#code-editor').inputValue();
await page.locator('#code-editor').fill(source.replace('RD=3300','RD=3400'));
await page.locator('#save-file').click();
await page.waitForFunction(()=>document.querySelector('#file-save-status').textContent.includes('Saved locally'));
await page.locator('[data-action=history]').click();
await page.locator('[data-restore]').first().waitFor();
console.log('EDITOR revision count',await page.locator('[data-restore]').count());
await page.locator('[data-action=new-file]').click();
await page.locator('#new-file-path').fill('testbenches/created.cir');
await page.locator('#new-file-content').fill(source);
await page.locator('#new-file-form button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#editor-file').value==='testbenches/created.cir');
console.log('FILE CREATE',await page.locator('#editor-file').inputValue());
await page.locator('.tabs [data-tab=workflows]').click();
await page.locator('[data-action=save-workflow]').click();
await page.locator('[data-action=run-workflow]').click();
await page.waitForFunction(()=>document.querySelector('#workflow-job')?.textContent.includes('succeeded'),{timeout:45000});
console.log('WORKFLOW',await page.locator('#workflow-job .badge').innerText(),await page.locator('#workflow-job tbody tr').count());
await page.locator('.tabs [data-tab=evaluation]').click();
await page.locator('#evaluation-form [name=episodes]').fill('2');
await page.locator('#evaluation-form button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#evaluation-job')?.textContent.includes('succeeded'),{timeout:30000});
console.log('EVALUATION',await page.locator('#evaluation-job .badge').innerText(),await page.locator('#evaluation-job tbody tr').count());
await page.locator('.tabs [data-tab=settings]').click();
await page.locator('[data-action=test-provider]').click();
await page.waitForFunction(()=>['success','error'].includes(document.querySelector('#provider-test-result')?.dataset.status));
console.log('PROVIDER EMPTY',await page.locator('#provider-test-result').innerText());
await page.locator('.tabs [data-tab=verification]').click();
console.log('VERIFICATION DRC disabled',await page.locator('[data-run-kind=drc]').isDisabled());
await page.setViewportSize({width:390,height:844});
await page.locator('.tabs [data-tab=overview]').click();
await page.screenshot({path:path.join(evidence, 'mobile.png'),fullPage:true});
console.log('MOBILE overflow',await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth));
console.log('PAGE_ERRORS',JSON.stringify(errors));
if (errors.length) throw new Error('Browser JavaScript errors: ' + errors.join('; '));
await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
