// Run against a disposable workspace. Exercises real layout and keyboard behavior.
const assert = require('node:assert/strict');
const {chromium} = require('playwright');

(async () => {
  const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
  try {
    const page = await browser.newPage({viewport:{width:1500,height:950}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.AF_URL || 'http://127.0.0.1:8765');
    await page.waitForFunction(() => !document.body.inert);
    assert.equal(await page.locator('#tree-resizer').count(), 1, 'Project explorer has an accessible resize control');
    const width = selector => page.locator(selector).evaluate(element => Math.round(element.getBoundingClientRect().width));
    const height = selector => page.locator(selector).evaluate(element => Math.round(element.getBoundingClientRect().height));
    await page.locator('#reset-layout').click();
    const initialTree = await width('.project-sidebar');
    await page.locator('#tree-resizer').focus();
    await page.keyboard.press('ArrowRight');
    assert.ok(await width('.project-sidebar') > initialTree, 'Right arrow grows the explorer');
    const resizedTree = await width('.project-sidebar');
    await page.reload();
    await page.waitForFunction(() => !document.body.inert);
    assert.equal(await width('.project-sidebar'), resizedTree, 'Panel dimensions survive reload');
    await page.locator('#ai-resizer').focus();
    const initialAI = await width('.ai-sidebar');
    await page.keyboard.press('ArrowLeft');
    assert.ok(await width('.ai-sidebar') > initialAI, 'Left arrow grows the assistant');
    await page.locator('#log-resizer').focus();
    const initialLog = await height('.log-panel');
    await page.keyboard.press('ArrowUp');
    assert.ok(await height('.log-panel') > initialLog, 'Up arrow grows the log');
    const box = await page.locator('#tree-resizer').boundingBox();
    const beforeDrag = await width('.project-sidebar');
    await page.mouse.move(box.x+box.width/2, box.y+40);
    await page.mouse.down();
    await page.mouse.move(box.x+65, box.y+40);
    assert.ok(await width('.project-sidebar') > beforeDrag, 'Pointer drag resizes the explorer');
    await page.keyboard.press('Escape');
    await page.mouse.up();
    assert.equal(await width('.project-sidebar'), beforeDrag, 'Escape cancels the drag');
    assert.equal(await page.locator('body').evaluate(element => element.classList.contains('resizing-panels')), false);
    await page.mouse.move(box.x+box.width/2, box.y+40);
    await page.mouse.down();
    await page.mouse.move(box.x+40, box.y+40);
    await page.locator('#tree-resizer').dispatchEvent('pointercancel');
    await page.mouse.up();
    assert.equal(await width('.project-sidebar'), beforeDrag, 'Pointer cancellation restores the previous width');
    assert.equal(await page.locator('body').evaluate(element => element.classList.contains('resizing-panels')), false);
    await page.locator('#tree-resizer').focus();
    await page.keyboard.press('Home');
    const minimum = await width('.project-sidebar');
    await page.keyboard.press('End');
    assert.ok(await width('.project-sidebar') > minimum, 'Home/End reach the panel bounds');
    await page.locator('#toggle-tree').click();
    assert.equal(await page.locator('.project-sidebar').isVisible(), false);
    assert.equal(await page.locator('#toggle-tree').getAttribute('aria-expanded'), 'false');
    await page.locator('#toggle-tree').click();
    assert.equal(await page.locator('.project-sidebar').isVisible(), true);
    await page.locator('#toggle-logs').click();
    assert.equal(await page.locator('#execution-log').isVisible(), false);
    assert.equal(await page.locator('#toggle-logs').getAttribute('aria-expanded'), 'false');
    assert.ok(await height('.log-panel') >= await height('.log-header'), 'Collapsed log retains the entire header');
    await page.locator('#toggle-logs').click();
    await page.locator('.tabs [data-tab=overview]').click();
    await page.keyboard.press('End');
    await page.waitForFunction(() => document.querySelector('.tabs [data-tab=settings]').getAttribute('aria-selected') === 'true');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.tab), 'settings');
    assert.equal(await page.locator('.tabs [tabindex="0"]').count(), 1, 'Workspace tabs use a single keyboard stop');
    await page.locator('.tabs [data-tab=desktop]').click();
    await page.locator('.skip-link').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'desktop-panel', 'Skip navigation reaches the active design panel');
    await page.locator('#reset-layout').click();
    assert.equal(await width('.project-sidebar'), initialTree, 'Reset restores the starting layout');
    await page.setViewportSize({width:700,height:800});
    await page.locator('#toggle-tree').click();
    assert.equal(await page.locator('#panel-backdrop').isVisible(), true);
    assert.equal(await page.locator('.central-workspace').evaluate(element => element.inert), true, 'Background cannot take focus behind the panel');
    assert.equal(await page.locator('.project-sidebar').evaluate(element => element.contains(document.activeElement)), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.project-sidebar').isVisible(), false);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'toggle-tree', 'Closing restores the trigger focus');
    await page.locator('#toggle-ai').click();
    await page.locator('#toggle-ai').click();
    assert.equal(await page.locator('.ai-sidebar').isVisible(), false, 'Mobile assistant toggle can close its drawer');
    await page.locator('#toggle-tree').click();
    await page.locator('#toggle-ai').click();
    assert.equal(await page.locator('.project-sidebar').isVisible(), false, 'Sidebar toggles can switch the active drawer');
    await page.locator('#panel-backdrop').click({position:{x:10,y:10}});
    assert.equal(await page.locator('.ai-sidebar').isVisible(), false);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'toggle-ai');
    assert.equal(await page.locator('.central-workspace').evaluate(element => element.inert), false);
    await page.locator('#toggle-ai').click();
    await page.locator('.ai-sidebar [data-tab=settings]').click();
    await page.locator('#panel-backdrop').waitFor({state:'hidden'});
    assert.equal(await page.locator('.central-workspace').evaluate(element => element.inert), false, 'Sidebar navigation exposes the requested view');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Panels fit the narrow viewport');
    await page.locator('#toggle-ai').click();
    await page.setViewportSize({width:1500,height:950});
    await page.locator('#panel-backdrop').waitFor({state:'hidden'});
    await page.setViewportSize({width:700,height:800});
    await page.waitForFunction(() => document.querySelector('#toggle-ai').getAttribute('aria-expanded') === 'false');
    assert.equal(await page.locator('.ai-sidebar').isVisible(), false, 'Returning to compact layout does not reopen an old drawer');
    await page.setViewportSize({width:1500,height:950});
    await page.locator('#log-resizer').focus();
    await page.keyboard.press('End');
    const preferredLog = await height('.log-panel');
    const storedLog = await page.evaluate(() => JSON.parse(localStorage.getItem('af-workspace-layout')).log);
    for (const viewport of [{width:844,height:390},{width:390,height:320}]) {
      await page.setViewportSize(viewport);
      await page.waitForFunction(() => document.querySelector('#main-content').getBoundingClientRect().height >= 100, null, {timeout:3000});
      assert.ok(await height('#main-content') >= 100, `Main workspace remains usable at ${viewport.width}×${viewport.height}`);
      assert.equal(await height('.log-panel'), Number(await page.locator('#log-resizer').getAttribute('aria-valuenow')), 'Log size matches its accessible value');
      assert.equal(await page.locator('.log-panel').evaluate(element => parseFloat(getComputedStyle(element).minHeight)), Number(await page.locator('#log-resizer').getAttribute('aria-valuemin')), 'Visual and accessible log minimum agree');
      assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('af-workspace-layout')).log), storedLog, 'Responsive clamping preserves the preferred log height');
    }
    await page.setViewportSize({width:1500,height:950});
    await page.waitForFunction(expected => Math.round(document.querySelector('.log-panel').getBoundingClientRect().height) === expected, preferredLog);
    assert.equal(await height('.log-panel'), preferredLog, 'Preferred log height returns on a larger viewport');
    assert.deepEqual(errors, []);
    console.log('PASS panel pointer/keyboard resizing, bounds, persistence/reset, tab navigation, and accessible mobile overlays');
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
