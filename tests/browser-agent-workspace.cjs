// Focused browser coverage for the agent controller, independent of the page layout.
const assert = require('node:assert/strict');
const path = require('node:path');
const {chromium} = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  try {
    const page = await browser.newPage();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('http://agent.test/', route => route.fulfill({body:'<!doctype html><body></body>',contentType:'text/html'}));
    await page.goto('http://agent.test/');
    await page.evaluate(() => {
      const selects = ['agent-backend','agent-mode','agent-session'];
      const buttons = ['agent-new','chat-send','agent-stop','agent-allow','agent-deny','agent-export','agent-history-toggle','agent-history-close','agent-add-context','agent-model-toggle','agent-model-apply','agent-commands','agent-scroll-bottom'];
      const inputs = ['agent-model','agent-model-search','agent-history-search'];
      const panels = ['agent-status','agent-diagnostic','assistant-model','assistant-backend','agent-permission-note','agent-context-note','agent-run-label','assistant-usage','chat-messages','agent-approval','agent-approval-tool','agent-approval-details','agent-proposed-file','agent-proposed-content','agent-recent','agent-history','agent-history-list','agent-context-picker','agent-project-files','agent-attachments','agent-model-picker','agent-model-options','agent-command-list','agent-export-menu'];
      document.body.innerHTML = selects.map(id => `<select id="${id}"></select>`).join('') + buttons.map(id => `<button type="button" id="${id}">${id}</button>`).join('') + inputs.map(id => `<input id="${id}">`).join('') + panels.map(id => `<div id="${id}"></div>`).join('') + '<input type="checkbox" id="agent-attach-run"><input type="file" multiple id="agent-file-input"><form id="chat-form"><textarea id="chat-input"></textarea></form>';
      for (const id of ['agent-export-menu','agent-context-picker','agent-model-picker','agent-command-list','agent-history']) document.getElementById(id).hidden = true;
      window.fixture = {requests:[],sessions:[],state:{settings:{provider:{model:'configured-model'}},context:new Set(),files:[{path:'test.cir'}]}};
    });
    await page.addScriptTag({path:path.resolve(__dirname,'../analog_factory/static/agent-content.js')});
    await page.addScriptTag({path:path.resolve(__dirname,'../analog_factory/static/agents.js')});
    await page.evaluate(async () => {
      const {fixture:f} = window;
      const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
      const t = (v, args={}) => v.replace(/\{(\w+)\}/g, (_, key) => args[key] ?? key);
      const html = (parts,...args) => typeof parts === 'string' ? parts : parts.reduce((out,part,i) => out+part+(args[i] ?? ''),'');
      f.ui = window.AFAgents.create({state:f.state,esc,t,html,formatDate:x=>x,number:String,onContextChange(){},api:async (url, options={}) => {
        f.requests.push({url,...options});
        if (url.startsWith('/api/agents')) return {backends:[{id:'api',name:'API',available:true,modes:['read-only','confirm']},{id:'codex',name:'Codex',available:true,modes:['read-only','workspace-write']}]};
        const parts = new URL(url,location.href).pathname.split('/'), project=parts[3], id=parts[6], action=parts[7];
        if (!id && options.method === 'POST') {const s={id:'s'+(f.sessions.length+1),project_id:project,...options.body,status:'idle',turns:[]};f.sessions.push(s);return structuredClone(s);}
        if (!id) {const q=new URL(url,location.href).searchParams.get('q')||'';return f.sessions.filter(s=>s.project_id===project && (!q||JSON.stringify(s).includes(q)));}
        const s=f.sessions.find(s=>s.id===id);
        if (action==='messages') {if(f.holdNextMessage){f.holdNextMessage=false;await new Promise(resolve=>{f.releaseMessage=resolve;});}s.status='succeeded';s.turns.push({id:'t'+s.turns.length,...structuredClone(options.body),reply:'done',status:'succeeded'});return structuredClone(s);}
        if (options.method==='PUT') Object.assign(s,options.body);
        if (options.method==='DELETE') {f.sessions=f.sessions.filter(s=>s.id!==id);return {};}
        return structuredClone(s);
      }});
      f.ui.bind();document.querySelector('#chat-form').addEventListener('submit',e=>{e.preventDefault();f.ui.send();});
      await f.ui.refreshCapabilities();await f.ui.selectProject('project-a');
    });
    await page.locator('#chat-input').fill('Unsaved draft');
    await page.locator('#agent-backend').selectOption('codex');
    assert.equal(await page.locator('#chat-input').inputValue(),'Unsaved draft','Changing agent must preserve the unsent draft');
    await page.locator('#agent-mode').selectOption('workspace-write');
    assert.equal(await page.locator('#chat-input').inputValue(),'Unsaved draft');
    await page.locator('#agent-model-toggle').click();
    await page.locator('#agent-model').fill('custom-circuit-model');
    await page.locator('#agent-model-apply').click();
    assert.equal(await page.locator('#chat-input').inputValue(),'Unsaved draft','Changing a model must preserve the draft');
    assert.equal(await page.locator('#assistant-model').innerText(),'custom-circuit-model');
    await page.locator('#agent-model-toggle').click();
    await page.locator('[data-agent-favorite="custom-circuit-model"]').click();
    assert.equal(await page.locator('[data-agent-favorite="custom-circuit-model"]').getAttribute('aria-pressed'),'true');
    await page.locator('#agent-model-search').fill('does-not-exist');
    assert.equal(await page.locator('[data-agent-model="custom-circuit-model"]').count(),0,'Model search filters actual saved models');
    await page.locator('#agent-model-search').press('Escape');
    await page.locator('#chat-input').dispatchEvent('keydown',{key:'Enter',isComposing:true});
    assert.equal(await page.evaluate(()=>window.fixture.requests.filter(r=>r.url.endsWith('/messages')).length),0,'IME Enter must not send');
    await page.locator('#agent-file-input').setInputFiles({name:'huge.txt',mimeType:'text/plain',buffer:Buffer.alloc(65537,65)});
    await page.locator('#agent-diagnostic').getByText('Each text attachment must fit within 64 KiB.').waitFor();
    assert.equal(await page.locator('[data-remove-attachment]').count(),0,'Oversized attachments are not retained');
    await page.locator('#agent-file-input').setInputFiles({name:'notes.txt',mimeType:'text/plain',buffer:Buffer.from('Circuit notes')});
    await page.locator('[data-remove-attachment]').waitFor();
    await page.evaluate(()=>window.fixture.ui.selectProject('project-b'));
    assert.equal(await page.locator('#chat-input').inputValue(),'','Project drafts do not leak');
    assert.equal(await page.locator('[data-remove-attachment]').count(),0);
    await page.evaluate(()=>window.fixture.ui.selectProject('project-a'));
    assert.equal(await page.locator('#chat-input').inputValue(),'Unsaved draft');
    assert.equal(await page.locator('[data-remove-attachment]').count(),1);
    await page.evaluate(() => {window.fixture.state.context.add('test.cir');window.fixture.state.run={id:'original-run'};window.fixture.ui.render();});
    await page.locator('#agent-attach-run').check();
    await page.locator('#chat-input').press('Shift+Enter');
    assert.match(await page.locator('#chat-input').inputValue(),/\n/);
    await page.locator('#chat-input').press('Enter');
    await page.waitForFunction(()=>window.fixture.requests.some(r=>r.url.endsWith('/messages')));
    const request=await page.evaluate(()=>window.fixture.requests.find(r=>r.url.endsWith('/messages')));
    assert.deepEqual(request.body.attachments,[{name:'notes.txt',content:'Circuit notes'}]);
    assert.equal(await page.locator('#chat-input').inputValue(),'');
    const downloadPromise=page.waitForEvent('download');
    await page.locator('#agent-export').click();
    await page.locator('[data-agent-export="json"]').click();
    const download=await downloadPromise;
    const chunks=[];for await (const chunk of await download.createReadStream()) chunks.push(chunk);
    assert.equal(JSON.parse(Buffer.concat(chunks).toString()).turns[0].message,'Unsaved draft','Export contains the actual turn');
    await page.evaluate(() => {window.fixture.state.context.clear();window.fixture.state.context.add('unrelated.cir');window.fixture.state.run={id:'another-run'};window.fixture.ui.render();});
    await page.locator('#agent-file-input').setInputFiles({name:'unrelated.txt',mimeType:'text/plain',buffer:Buffer.from('Other draft context')});
    await page.locator('#agent-attachments').getByText('unrelated.txt',{exact:true}).waitFor();
    await page.locator('[data-agent-action="edit-resend"]').click();
    assert.equal(await page.locator('#chat-input').inputValue(),'Unsaved draft','Edit and resend fills an editable composer');
    assert.deepEqual(await page.evaluate(()=>[...window.fixture.state.context]),['test.cir'],'Edit and resend restores original project files');
    assert.equal(await page.locator('#agent-attachments').getByText('notes.txt',{exact:true}).count(),1,'Edit and resend restores original local text');
    assert.equal(await page.locator('#agent-attachments').getByText('unrelated.txt',{exact:true}).count(),0,'Unrelated draft attachments are replaced');
    assert.match(await page.locator('#agent-run-label').innerText(),/original/,'The composer identifies the original run, not the currently selected run');
    assert.equal(await page.evaluate(()=>window.fixture.requests.filter(r=>r.url.endsWith('/messages')).length),1,'Edit and resend never sends automatically');
    await page.evaluate(async()=>{window.fixture.state.run=null;await window.fixture.ui.selectProject('project-b');await window.fixture.ui.selectProject('project-a');});
    assert.deepEqual(await page.evaluate(()=>[...window.fixture.state.context]),['test.cir'],'Resend context persists with the conversation draft');
    assert.equal(await page.locator('#agent-attach-run').isChecked(),true,'The original run remains attached even with no run selected in the workspace');
    await page.locator('#chat-input').fill('Edited review');
    await page.locator('#chat-input').press('Enter');
    await page.waitForFunction(()=>window.fixture.requests.filter(r=>r.url.endsWith('/messages')).length===2);
    const resent=await page.evaluate(()=>window.fixture.requests.filter(r=>r.url.endsWith('/messages')).at(-1).body);
    assert.deepEqual(resent,{message:'Edited review',files:['test.cir'],attachments:[{name:'notes.txt',content:'Circuit notes'}],run_id:'original-run'},'Resending uses the original context and edited message');
    await page.evaluate(()=>{window.fixture.holdNextMessage=true;});
    await page.locator('#chat-input').fill('Request in flight');
    await page.locator('#chat-input').press('Enter');
    await page.waitForFunction(()=>Boolean(window.fixture.releaseMessage));
    assert.equal(await page.locator('#agent-backend').isDisabled(),true,'A pending send locks the backend');
    await page.locator('#chat-input').fill('Next draft while request is pending');
    await page.locator('[data-agent-action="edit-resend"]').first().click();
    assert.equal(await page.locator('#chat-input').inputValue(),'Next draft while request is pending','Resend cannot replace a draft while a send is pending');
    await page.evaluate(()=>window.fixture.releaseMessage());
    await page.waitForFunction(()=>!document.querySelector('#agent-backend').disabled);
    assert.equal(await page.locator('#chat-input').inputValue(),'Next draft while request is pending','Late send completion preserves the next draft');
    await page.locator('#chat-input').fill('/review');
    await page.locator('#chat-input').press('Enter');
    assert.match(await page.locator('#chat-input').inputValue(),/^Review the selected circuit files/,'Slash commands insert a relevant prompt');
    await page.locator('#agent-commands').click();
    await page.locator('[data-agent-manage-quick]').click();
    await page.locator('#agent-quick-message-dialog [name=title]').fill('My review');
    await page.locator('#agent-quick-message-dialog [name=message]').fill('Inspect bias stability.');
    await page.locator('[data-save-quick]').click();
    await page.locator('#agent-commands').click();
    await page.locator('[data-agent-quick="0"]').click();
    assert.equal(await page.locator('#chat-input').inputValue(),'Inspect bias stability.','Quick messages remain editable before sending');
    await page.locator('#chat-input').fill('Session draft');
    await page.locator('#agent-new').click();
    assert.equal(await page.locator('#chat-input').inputValue(),'');
    await page.locator('#agent-history-toggle').click();
    await page.locator('#agent-history-list [data-agent-session="s1"]').click();
    assert.equal(await page.locator('#chat-input').inputValue(),'Session draft');
    await page.locator('#agent-history-toggle').click();
    await page.locator('#agent-history-search').fill('done');
    await page.waitForFunction(()=>window.fixture.requests.some(r=>r.url.includes('?q=done')));
    page.once('dialog',dialog=>dialog.accept('Renamed conversation'));
    await page.locator('[data-agent-rename="s1"]').click();
    await page.waitForFunction(()=>window.fixture.requests.some(r=>r.method==='PUT'));
    assert.equal(await page.evaluate(()=>window.fixture.sessions[0].title),'Renamed conversation');
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('[data-agent-delete="s1"]').click();
    await page.waitForFunction(()=>window.fixture.sessions.length===0);
    assert.deepEqual(errors,[]);
    console.log('Agent workspace controller passed: drafts, attachments, Enter, history, search, rename and delete.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
